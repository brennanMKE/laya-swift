#!/usr/bin/env zsh
# Copy laya-go's Metal shaders and golden fixtures into this package and
# record the laya-go commit they came from (see docs/swift-port.md).
#
# Usage: scripts/sync-from-laya-go.sh [path/to/laya-go]   (default: ../laya-go)

set -euo pipefail

ROOT="${0:A:h:h}"
LAYA_GO="${1:-$ROOT/../laya-go}"
LAYA_GO="${LAYA_GO:A}"
[[ -f "$LAYA_GO/internal/metal/shaders.metal" ]] || { print -u2 "error: no laya-go checkout at $LAYA_GO"; exit 1; }

commit="$(git -C "$LAYA_GO" rev-parse HEAD)"
if [[ -n "$(git -C "$LAYA_GO" status --porcelain -- internal/metal testdata/golden)" ]]; then
    print -u2 "warning: laya-go has uncommitted changes to the shaders or fixtures"
fi

# Shaders as a raw string literal, compiled at load like laya-go does.
out="$ROOT/Sources/LayaMetal/ShaderSource.swift"
{
    print "// Generated by scripts/sync-from-laya-go.sh from laya-go $commit"
    print "// internal/metal/shaders.metal. Do not edit; run the script instead."
    print ""
    print "enum ShaderSource {"
    print "    static let laya = ##\"\"\""
    cat "$LAYA_GO/internal/metal/shaders.metal"
    print "\"\"\"##"
    print "}"
} > "$out"

# Golden fixtures for the parity tests.
dest="$ROOT/Tests/LayaCoreTests/Resources/golden"
rm -rf "$dest"
mkdir -p "$dest"
rsync -a --exclude corpus "$LAYA_GO/testdata/golden/" "$dest/"

print "$commit" > "$ROOT/LAYA_GO_COMMIT"
print "Synced laya-go $commit"
print "  $out"
print "  $dest ($(du -sh "$dest" | cut -f1))"
